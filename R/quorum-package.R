#' quorum: The Orchestra's Consensus Layer
#'
#' Lenses in, a typed verdict out. quorum registers any member's estimate of a
#' shared estimand as a lens with declared independence, expressiveness and
#' scope, compares a quorum of lenses with the hub's agreement semantics, and
#' resolves the comparison through a declared policy into a typed verdict and
#' an orchestra manifest. A quorum of independent lenses must agree before an
#' answer is carried; no quorum means abstain. The package also carries the
#' on-ramps by which non-hub estimates become lenses: ensemble-source
#' ingestion, surrogate emulators, ensemble-derived priors, posterior
#' predictive checks and the koine fourth-opinion backend.
#'
